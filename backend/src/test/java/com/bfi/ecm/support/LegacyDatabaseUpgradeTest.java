package com.bfi.ecm.support;

import io.zonky.test.db.postgres.embedded.EmbeddedPostgres;
import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.output.MigrateResult;
import org.junit.jupiter.api.Test;

import javax.sql.DataSource;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

class LegacyDatabaseUpgradeTest {

    @Test
    void baselinesExistingSchemaAndAppliesOnlyNewMigrations() throws Exception {
        try (EmbeddedPostgres postgres = EmbeddedPostgres.start()) {
            DataSource dataSource = postgres.getPostgresDatabase();
            try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
                statement.execute(Files.readString(Path.of("src/main/resources/db/migration/V1__baseline.sql")));
                statement.execute("create table directory (id bigint primary key, name varchar(255), path varchar(255))");
                statement.execute("insert into _user (uuid, email, account_locked, enabled, role) values ('u-1', 'admin@admin.com', false, true, 'ADMIN')");
                statement.execute("""
                        create table refresh_token (
                            created_at TIMESTAMP, expires_at timestamp(6) with time zone not null,
                            id bigint generated by default as identity, revoked_at timestamp(6) with time zone,
                            updated_at TIMESTAMP, user_id bigint not null references _user,
                            token_hash varchar(64) not null unique, family_id varchar(255) not null,
                            uuid varchar(255) not null unique, primary key (id))
                        """);
            }

            MigrateResult result = Flyway.configure()
                    .dataSource(dataSource)
                    .baselineOnMigrate(true)
                    .baselineVersion("1")
                    .load()
                    .migrate();

            assertThat(result.success).isTrue();
            assertThat(result.migrations).extracting(migration -> migration.version).containsExactly("2");
            try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement();
                 ResultSet users = statement.executeQuery("select count(*) from _user")) {
                users.next();
                assertThat(users.getInt(1)).isEqualTo(1);
            }
        }
    }
}
