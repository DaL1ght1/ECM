create table if not exists refresh_token (
    id         bigint generated by default as identity primary key,
    uuid       varchar(255)             not null unique,
    created_at timestamp,
    updated_at timestamp,
    token_hash varchar(64)              not null unique,
    family_id  varchar(255)             not null,
    user_id    bigint                   not null references _user,
    expires_at timestamp(6) with time zone not null,
    revoked_at timestamp(6) with time zone
);

create index if not exists ix_refresh_token_family on refresh_token (family_id);
create index if not exists ix_refresh_token_user on refresh_token (user_id);

create table folder (
    id         bigint generated by default as identity primary key,
    uuid       varchar(255) not null unique,
    created_at timestamp,
    updated_at timestamp,
    name       varchar(255) not null,
    parent_id  bigint references folder,
    owner_id   bigint       not null references _user
);

create index ix_folder_parent on folder (parent_id);
create unique index ux_folder_child_name on folder (parent_id, lower(name)) where parent_id is not null;
create unique index ux_folder_top_level_name on folder (owner_id, lower(name)) where parent_id is null;

create table document (
    id                 bigint generated by default as identity primary key,
    uuid               varchar(255) not null unique,
    created_at         timestamp,
    updated_at         timestamp,
    name               varchar(255) not null,
    folder_id          bigint references folder,
    owner_id           bigint       not null references _user,
    current_version_id bigint,
    lock_version       bigint       not null default 0,
    deleted_at         timestamp(6) with time zone
);

create index ix_document_folder on document (folder_id);
create index ix_document_owner on document (owner_id);
create unique index ux_document_live_name on document (folder_id, lower(name))
    where folder_id is not null and deleted_at is null;
create unique index ux_document_top_level_live_name on document (owner_id, lower(name))
    where folder_id is null and deleted_at is null;

create table document_version (
    id             bigint generated by default as identity primary key,
    uuid           varchar(255) not null unique,
    created_at     timestamp,
    updated_at     timestamp,
    document_id    bigint       not null references document,
    version_number integer      not null,
    blob_key       varchar(36)  not null,
    sha256         varchar(64)  not null,
    size           bigint       not null,
    mime_type      varchar(255) not null,
    comment        varchar(500),
    created_by_id  bigint       not null references _user,
    unique (document_id, version_number)
);

create index ix_document_version_blob on document_version (blob_key);

alter table document
    add constraint fk_document_current_version foreign key (current_version_id) references document_version;

create table folder_permission (
    id             bigint generated by default as identity primary key,
    uuid           varchar(255) not null unique,
    created_at     timestamp,
    updated_at     timestamp,
    folder_id      bigint       not null references folder,
    principal_type varchar(10)  not null check (principal_type in ('USER', 'ROLE')),
    principal      varchar(255) not null,
    access         varchar(10)  not null check (access in ('READ', 'WRITE')),
    unique (folder_id, principal_type, principal)
);

create index ix_folder_permission_principal on folder_permission (principal_type, principal);
